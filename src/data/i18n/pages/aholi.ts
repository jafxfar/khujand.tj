const formatMahalla = (m: Mahalla, lang: Locale): string => {
  const name = pick(m.name, lang)
  const popLabel =
    lang === 'ru' ? 'население' : lang === 'en' ? 'population' : 'аҳолӣ'
  const chairLabel = lang === 'ru' ? 'раис' : lang === 'en' ? 'chair' : 'раис'
  const areaLabel = lang === 'ru' ? 'территория' : lang === 'en' ? 'area' : 'ҳудуд'
  return `${m.n}. ${name} — ${chairLabel}: ${m.chair}; тел.: ${m.phone}; ${popLabel}: ${m.population}. ${areaLabel}: ${m.areaTg}`
}

export const getAholiArticle = (lang: Locale): SiteArticle => {
  const ui = getUi(lang)

  return {
    slug: 'aholi',
    title: pick(title, lang),
    date: pick(date, lang),
    paragraphs: [pick(intro, lang), ...mahallas.map((m) => formatMahalla(m, lang))],
    rating: { votes: 18, average: 4.28, max: 5 },
    crumbs: [
      { label: ui.breadcrumb, href: withLangPath('/', lang) },
      { label: ui.forResidents },
      { label: ui.forCityResidents },
    ],
  }
}
